import type { ModelCapability, PricingModel } from '../types'

// ----------------------------------------------------------------------------
// Backend-provided catalog metadata (capabilities, modalities)
// ----------------------------------------------------------------------------

export const CAPABILITY_LABEL_KEYS: Record<ModelCapability, string> = {
  function_calling: 'Function calling',
  streaming: 'Streaming',
  vision: 'Vision',
  json_mode: 'JSON mode',
  structured_output: 'Structured output',
  reasoning: 'Reasoning',
  tools: 'Tools',
  system_prompt: 'System prompt',
  web_search: 'Web search',
  code_interpreter: 'Code interpreter',
  caching: 'Prompt caching',
  embeddings: 'Embeddings',
}

export const MODALITY_LABEL_KEYS: Record<string, string> = {
  text: 'Text',
  image: 'Image',
  audio: 'Audio',
  video: 'Video',
  file: 'File',
}

export function normalizeCatalogItems(items?: readonly string[]): string[] {
  if (!items) return []
  return items.filter((item) => item.trim().length > 0)
}

/** i18n keys for the capabilities the backend explicitly reports. */
export function getModelCapabilityLabelKeys(model: PricingModel): string[] {
  return normalizeCatalogItems(model.capabilities).map(
    (capability) =>
      CAPABILITY_LABEL_KEYS[capability as ModelCapability] ?? capability
  )
}
